def render(steps):
    lines = ["mini_script:"]
    for i, (text, dur, voice, clk) in enumerate(steps, 1):
        lines.append(f"  - step: {i}")
        lines.append(f"    instruction: {text}")
        lines.append(f"    duration_sec: {dur}")
        lines.append(f"    voice: {'true' if voice else 'false'}")
        lines.append(f"    clicker_hint: {'true' if clk else 'false'}")
    return "\n".join(lines) + "\n"


def main() -> int:
    bad = 0
    for sid, steps in MINI.items():
        total = sum(s[1] for s in steps)
        if total > 300:
            print(f"ERROR {sid}: mini_script {total}s > 300")
            bad += 1
            continue
        if not any(s[3] for s in steps):
            print(f"ERROR {sid}: 没有 clicker_hint=true")
            bad += 1
            continue
        path = os.path.join(ROOT, f"{sid}.yaml")
        text = open(path, encoding="utf-8").read()
        if "\nmini_script:" in text:
            print(f"SKIP  {sid}: 已有 mini_script")
            continue
        marker = "\nscoring_hint:"
        if marker not in text:
            print(f"ERROR {sid}: 找不到 scoring_hint")
            bad += 1
            continue
        text = text.replace(marker, "\n" + render(steps) + "scoring_hint:", 1)
        open(path, "w", encoding="utf-8").write(text)
        print(f"OK    {sid}: {len(steps)} 步 {total}s")
    missing = sorted(set(os.path.splitext(f)[0] for f in os.listdir(ROOT) if f.endswith(".yaml")) - set(MINI))
    if missing:
        print(f"ERROR 未覆盖的技能: {missing}")
        bad += 1
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
